// 按长度降序，保证最长匹配优先
const TOKENS = TOKENS_RAW.slice().sort((a, b) => b[0].length - a[0].length);

function hasCJK(s) {
  return /[一-鿿]/.test(s);
}
function normalizePunct(s) {
  return s
    .replace(/[，、]/g, ", ")
    .replace(/[。！？]/g, ". ")
    .replace(/[：；]/g, ": ")
    .replace(/[（]/g, " (")
    .replace(/[）]/g, ") ")
    .replace(/[「『]/g, "'")
    .replace(/[」』]/g, "'")
    .replace(/[—–－]/g, "-")
    .replace(/[　]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}
function tokenize(s) {
  let out = s;
  for (const [zh, en] of TOKENS) {
    if (!zh) continue;
    out = out.split(zh).join(en);
  }
  return normalizePunct(out);
}

// stock 键（addCommand 的 langKey）是 ASCII 名，需要显式映射到英文值
const STOCK = {
  addTask: "New To-do",
  syncNow: "Sync Now",
  openPanel: "Open Calendar & Tasks",
  insertToday: "Insert Schedule & Todos into Daily Note",
};

const result = {};
let exactN = 0;
let tokenN = 0;
let stockN = 0;
let fallbackN = 0;
// 始终以 zh_CN 为唯一来源（key 列表 + 中文原文），避免二次运行读到陈旧的 en_US 而漂移
for (const k of Object.keys(zh)) {
  if (EXACT.has(k)) {
    result[k] = EXACT.get(k);
    exactN++;
  } else if (Object.prototype.hasOwnProperty.call(STOCK, k)) {
    result[k] = STOCK[k];
    stockN++;
  } else {
    const t = tokenize(k);
    if (!hasCJK(t)) {
      result[k] = t;
      tokenN++;
    } else {
      // 仍含中文：保留中文原文（回退，英文环境看到中文也不白屏）
      result[k] = k;
      fallbackN++;
    }
  }
}

fs.writeFileSync(EN, JSON.stringify(result, null, 2) + "\n", "utf8");
console.log(
  `en_US.json 翻译统计：精确 ${exactN} / 词级 ${tokenN} / stock预翻 ${stockN} / 回退中文 ${fallbackN} / 共 ${Object.keys(result).length}`
);
